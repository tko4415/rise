            </h3>
          </div>
          <div class="answer">
            <h3 class="heading">
              <span class="qa a">A</span>
              <span class="main">立退料には相場はありません｡</span>
            </h3>
            <div class="body">
              <p>借地借家法の考え方では、賃貸人側の建物使用の必要性、賃借人側の建物使用の必要性などの諸事情を総合的に考慮した上で、立退料が算定されることになります。そのため、「賃料の○ヶ月分」というような明確な相場はありません。ただ弁護士の知見で見立てを示すことは可能です。<br>
                通常、弁護⼠介⼊前の提⽰では引越し分程度であることが多いです。<br>
                これでも⼗分と思われる⽅もいるかもしれませんが、実はこれでもまだ正当な⽴退料の額には程遠いことが多くあります。本来の考え方では、引越し費用以外に正当事由を補填する費用も要求できるという考え方のもと、弁護士が交渉することにより、正当な立退料を要求することができます。</p>
